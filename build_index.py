#!/usr/bin/env python3
"""
Scans the 'pages' folder for .html files and writes index.js,
which the search bar uses. Run it again every time you add,
remove or edit a page:

    python3 build_index.py

Optional meta tags you can put in the <head> of each page to
customize how it appears in the results:

    <title>My custom title</title>
    <meta name="description" content="The preview text shown under the title.">
    <meta name="keywords" content="france, students, 1968">
    <meta name="date" content="15/05/1968">          (default: file modified date)
    <meta name="source" content="Manifesto">         (default: Manifesto)
    <meta name="verified" content="true">            (shows the verified icon)
"""
import json
import os
import sys
from datetime import datetime
from html.parser import HTMLParser

ROOT = os.path.dirname(os.path.abspath(__file__))
PAGES_DIR = os.path.join(ROOT, "pages")
OUT_FILE = os.path.join(ROOT, "index.js")


class PageParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.meta = {}
        self.title = ""
        self.text = []
        self._in_title = False
        self._skip = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag == "title":
            self._in_title = True
        elif tag in ("script", "style"):
            self._skip += 1
        elif tag == "meta" and a.get("name") and a.get("content") is not None:
            self.meta[a["name"].lower()] = a["content"].strip()

    def handle_endtag(self, tag):
        if tag == "title":
            self._in_title = False
        elif tag in ("script", "style") and self._skip:
            self._skip -= 1

    def handle_data(self, data):
        if self._in_title:
            self.title += data
        elif not self._skip:
            self.text.append(data)


def read_page(path):
    for enc in ("utf-8", "latin-1"):
        try:
            with open(path, encoding=enc) as f:
                return f.read()
        except UnicodeDecodeError:
            continue
    return ""


def main():
    if not os.path.isdir(PAGES_DIR):
        os.makedirs(PAGES_DIR)
        print("Created empty 'pages' folder. Put your .html files in it and run again.")

    docs = []
    for folder, _, files in os.walk(PAGES_DIR):
        for name in sorted(files):
            if not name.lower().endswith((".html", ".htm")):
                continue
            path = os.path.join(folder, name)
            parser = PageParser()
            parser.feed(read_page(path))

            rel = os.path.relpath(path, ROOT).replace(os.sep, "/")
            title = parser.title.strip() or os.path.splitext(name)[0].replace("-", " ").replace("_", " ")
            text = " ".join(" ".join(parser.text).split())
            date = parser.meta.get("date") or datetime.fromtimestamp(os.path.getmtime(path)).strftime("%d/%m/%Y")

            docs.append({
                "href": rel,
                "title": title,
                "description": parser.meta.get("description", ""),
                "keywords": parser.meta.get("keywords", ""),
                "source": parser.meta.get("source", "Manifesto"),
                "verified": parser.meta.get("verified", "").lower() in ("true", "yes", "1"),
                "date": date,
                "text": text,
            })

    with open(OUT_FILE, "w", encoding="utf-8") as f:
        f.write("// Generated by build_index.py. Do not edit by hand.\n")
        f.write("window.ARCHIVE = " + json.dumps(docs, ensure_ascii=False, indent=2) + ";\n")

    print(f"Indexed {len(docs)} page(s) -> index.js")


if __name__ == "__main__":
    sys.exit(main())
